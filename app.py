import os
import logging
from typing import List
from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

from src.graph import build_rag_graph
from src.config import PINECONE_INDEX_NAME, API_HOST, API_PORT, has_live_credentials

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger(__name__)

# Initialize FastAPI application
app = FastAPI(
    title="Agentic AI RAG Chatbot API",
    description="Production RAG API powered by LangGraph, Pinecone, and OpenAI for the Agentic AI eBook.",
    version="1.0.0",
)

# Enable CORS for frontend / web integrations
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# Initialize compiled LangGraph workflow
graph = build_rag_graph(index_name=PINECONE_INDEX_NAME)


# Request and Response schemas
class QueryRequest(BaseModel):
    query: str = Field(..., description="The user's question regarding the Agentic AI eBook", min_length=1)

    model_config = {
        "json_schema_extra": {
            "example": {"query": "What is Agentic AI according to the eBook?"}
        }
    }


class QueryResponse(BaseModel):
    final_answer: str = Field(..., description="The grounded answer generated by the RAG system")
    retrieved_context: List[str] = Field(..., description="List of source text chunks retrieved for grounding")
    confidence_score: float = Field(..., description="Confidence / relevance score between 0.0 and 1.0")


@app.get("/", tags=["Health"])
async def root():
    return {
        "project": "Agentic AI RAG Chatbot",
        "status": "online",
        "documentation": "/docs",
        "endpoints": {
            "chat": "POST /chat",
            "health": "GET /health",
        },
        "live_credentials_configured": has_live_credentials(),
    }


@app.get("/health", tags=["Health"])
async def health_check():
    return {
        "status": "healthy",
        "pinecone_index": PINECONE_INDEX_NAME,
        "credentials_configured": has_live_credentials(),
    }


@app.post("/chat", response_model=QueryResponse, tags=["RAG Workflow"])
async def chat_endpoint(request: QueryRequest):
    """
    RAG Chat endpoint:
    1. Executes LangGraph execution graph: retrieve -> generate
    2. Enforces strict document grounding
    3. Returns final answer, source chunks, and confidence score
    """
    if not request.query.strip():
        raise HTTPException(status_code=400, detail="Query cannot be empty.")

    try:
        initial_state = {
            "question": request.query.strip(),
            "context": [],
            "answer": "",
            "score": 0.0,
        }
        
        result = graph.invoke(initial_state)

        return QueryResponse(
            final_answer=result.get("answer", "I cannot answer based on the provided document."),
            retrieved_context=result.get("context", []),
            confidence_score=result.get("score", 0.0),
        )
    except Exception as e:
        logger.error(f"Error executing RAG graph: {e}", exc_info=True)
        raise HTTPException(status_code=500, detail=f"Failed to process query: {str(e)}")


if __name__ == "__main__":
    import uvicorn
    uvicorn.run("app:app", host=API_HOST, port=API_PORT, reload=True)
